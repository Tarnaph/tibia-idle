export function formatNumberWithDots(val: number): string {
  if (typeof val !== 'number' || isNaN(val)) return '0';
  return val.toLocaleString('pt-BR');
}

export function getDifficultyStars(stars: number, maxStars = 4): { filled: number; total: number } {
  const filled = Math.max(0, Math.min(maxStars, Math.round(stars)));
  return { filled, total: maxStars };
}
