export interface ItemEntry {
  id: number;
  name: string;
  category: string;
  attack: number;
  defense: number;
  twoHanded: boolean;
  level: number;
  vocations: string[];
  imbuements: string;
  categoriesText: string;
  price: number;
  droppedBy: string[];
  spriteUrl: string;
}

export type CyclopediaItem = ItemEntry;

export interface ElementalResistances {
  physical: number; // -100 to 100 (% of damage modification/resistance)
  energy: number;
  earth: number;
  fire: number;
  ice: number;
  holy: number;
  death: number;
}

export interface BestiaryMonster {
  id: string;
  name: string;
  stars: number; // 1 to 4
  difficulty: 'Fácil' | 'Médio' | 'Difícil' | 'Extremo';
  killsNeeded: number; // e.g. 250, 500, 1000
  hp: number;
  exp: number;
  speed: number;
  armor: number;
  spriteUrl: string;
  resistances: ElementalResistances;
  drops: Array<{
    id: number;
    name: string;
    rare: boolean;
    count?: number;
  }>;
  locations: string[];
}

export interface BosstiaryBoss {
  id: string;
  name: string;
  tier: 'Archfoe' | 'Bane' | 'Nemesis';
  stars: number; // 1 to 3
  prowess: number;
  expertise: number;
  mastery: number;
  hp: number;
  exp: number;
  summons: string[];
  cooldown: string;
  spriteUrl: string;
  resistances: ElementalResistances;
  dropsCommon: Array<{ id: number; name: string }>;
  dropsRare: Array<{ id: number; name: string }>;
}

